CREATE FUNCTION portaria_json_text(body TEXT,path TEXT) RETURNS TEXT LANGUAGE SQL IMMUTABLE STRICT AS $$
 SELECT CASE jsonb_typeof(body::jsonb #> string_to_array(substr(path,3),'.'))
 WHEN 'boolean' THEN CASE body::jsonb #>> string_to_array(substr(path,3),'.') WHEN 'true' THEN '1' ELSE '0' END
 ELSE body::jsonb #>> string_to_array(substr(path,3),'.') END;
$$;
