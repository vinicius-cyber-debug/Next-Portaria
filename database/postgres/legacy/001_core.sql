CREATE FUNCTION portaria_guard() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 PERFORM 1 FROM operational_meta WHERE id=1 FOR UPDATE;
 IF NOT EXISTS(SELECT 1 FROM operational_meta WHERE id=1 AND revision=NEW.expected_revision) THEN RAISE EXCEPTION 'REVISION_CONFLICT'; END IF;
 IF NOT EXISTS(SELECT 1 FROM operational_users WHERE id=NEW.actor_id AND role=NEW.actor_role AND status='active') THEN RAISE EXCEPTION 'ACCESS_REVOKED'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER operational_revision_guard BEFORE INSERT ON operational_mutation_guard FOR EACH ROW EXECUTE FUNCTION portaria_guard();
CREATE FUNCTION portaria_audit_immutable() RETURNS TRIGGER LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'AUDIT_IMMUTABLE'; END $$;
CREATE TRIGGER operational_audit_immutable BEFORE UPDATE OR DELETE ON operational_audit FOR EACH ROW EXECUTE FUNCTION portaria_audit_immutable();
CREATE FUNCTION portaria_last_admin() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.role='admin' AND OLD.status='active' AND (TG_OP='DELETE' OR NEW.role<>'admin' OR NEW.status<>'active') THEN
  PERFORM pg_advisory_xact_lock(hashtext('portaria-last-admin'));
  IF (SELECT count(*) FROM operational_users WHERE role='admin' AND status='active')<=1 THEN RAISE EXCEPTION 'LAST_ADMIN'; END IF;
  IF EXISTS(SELECT 1 FROM operational_credentials WHERE user_id=OLD.id) AND
   (SELECT count(*) FROM operational_users u JOIN operational_credentials c ON c.user_id=u.id WHERE u.role='admin' AND u.status='active')<=1 THEN RAISE EXCEPTION 'LAST_ADMIN'; END IF;
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF; RETURN NEW;
END $$;
CREATE TRIGGER operational_last_admin_update BEFORE UPDATE OF role,status ON operational_users FOR EACH ROW EXECUTE FUNCTION portaria_last_admin();
CREATE TRIGGER operational_last_admin_delete BEFORE DELETE ON operational_users FOR EACH ROW EXECUTE FUNCTION portaria_last_admin();
